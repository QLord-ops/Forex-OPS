/* global URL, console */
// Writes src/theme-tokens.css: every themed colour as an "r g b" variable, light on :root, dark under [data-theme="dark"].
// Variables are named by role and light hex (--bg-f1f5f9, --tx-0f172a, --ln-e2e8f0) so a light value never changes by accident.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import colors from 'tailwindcss/colors.js'
import { TAILWIND_PALETTES, darkOf, normalize, triplet } from './theme-palette.mjs'

const root = fileURLToPath(new URL('..', import.meta.url))
const sources = ['src/styles.css', 'src/components/truck-card.css', 'src/components/dispatcher-assistant.css']
const used = new Set()
for (const file of sources) for (const m of readFileSync(root + file, 'utf8').matchAll(/--(bg|tx|ln)-([0-9a-f]{6})\b/g)) used.add(`${m[1]}-${m[2]}`)
for (const palette of TAILWIND_PALETTES) for (const value of Object.values(colors[palette])) for (const role of ['bg', 'tx', 'ln']) used.add(`${role}-${normalize(value).slice(1)}`)
used.add('bg-ffffff')

const names = [...used].sort()
const line = (name, dark) => {
  const [role, h] = name.split('-')
  return `  --${name}: ${triplet(dark ? darkOf('#' + h, role) : '#' + h)};`
}
const css = `/* Generated by scripts/theme-tokens.mjs — do not edit by hand. */
:root, [data-theme="light"] {
${names.map((n) => line(n, false)).join('\n')}
}
[data-theme="dark"] {
${names.map((n) => line(n, true)).join('\n')}
}
`
writeFileSync(root + 'src/theme-tokens.css', css)
console.log(`theme-tokens.css: ${names.length} colours`)
